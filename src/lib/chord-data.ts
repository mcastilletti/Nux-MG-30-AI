export function getChordPositions(chordName: string): string[] | null {
  if (!chordName) return null;

  // Cerca la radice più lunga corrispondente (es. "C#" invece di "C")
  const roots = Object.keys(CHORD_POSITIONS_DATA).sort((a, b) => b.length - a.length);
  let matchedRoot = "";
  for (const root of roots) {
    if (chordName.startsWith(root)) {
      matchedRoot = root;
      break;
    }
  }

  if (!matchedRoot) return null;

  const quality = chordName.slice(matchedRoot.length).trim();
  const entry = CHORD_POSITIONS_DATA[matchedRoot];

  if (quality === "") return entry.major;

  // Gestione diretta per Slash Chords e varianti mappate esplicitamente
  if (entry[quality]) {
    return entry[quality];
  }

  // Fallback per qualità standard
  switch (quality) {
    case "m": return entry.m;
    case "7": return entry["7"];
    case "maj7": return entry.maj7;
    case "m7": return entry.m7;
    case "aum": return entry.aum;
    case "dim": return entry.dim;
    case "sus4": return entry.sus4;
    case "sus2": return entry.sus2;
    case "add9": return entry.add9;
    default: return entry.major; 
  }
}
